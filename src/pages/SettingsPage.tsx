import { useEffect, useState } from "react";
import { Moon, Sun, Monitor, Cpu, WifiOff, RefreshCw, Download, Trash2, RotateCcw } from "lucide-react";
import { useChats, usePortfolio, useSettings, type Theme } from "@/store";
import { aiStatus, type AIStatus } from "@/lib/ai";
import { cn } from "@/lib/format";
import { Page, PageHeader, Segmented, Toggle } from "@/components/ui";

function Section({ title, desc, children }: { title: string; desc?: string; children: React.ReactNode }) {
  return (
    <section className="card p-5">
      <h2 className="font-medium">{title}</h2>
      {desc && <p className="mt-0.5 text-sm text-muted">{desc}</p>}
      <div className="mt-4 divide-y divide-line">{children}</div>
    </section>
  );
}

function Row({ label, hint, children }: { label: string; hint?: string; children: React.ReactNode }) {
  return (
    <div className="flex flex-wrap items-center justify-between gap-3 py-3 first:pt-0 last:pb-0">
      <div>
        <div className="text-sm">{label}</div>
        {hint && <div className="text-xs text-muted">{hint}</div>}
      </div>
      {children}
    </div>
  );
}

export function SettingsPage() {
  const s = useSettings();
  const resetPortfolio = usePortfolio((p) => p.reset);
  const clearChats = useChats((c) => c.clearAll);
  const [status, setStatus] = useState<AIStatus | null>(null);
  const [confirm, setConfirm] = useState<null | "chats" | "portfolio">(null);
  useEffect(() => { aiStatus().then(setStatus); }, []);

  const exportData = () => {
    const data = { exportedAt: new Date().toISOString(), settings: useSettings.getState(), portfolio: usePortfolio.getState(), conversations: useChats.getState().conversations };
    const url = URL.createObjectURL(new Blob([JSON.stringify(data, (_k, v) => (typeof v === "function" ? undefined : v), 2)], { type: "application/json" }));
    const a = Object.assign(document.createElement("a"), { href: url, download: "equidy-export.json" });
    a.click();
    URL.revokeObjectURL(url);
  };

  const themes: { v: Theme; label: string; icon: typeof Sun }[] = [
    { v: "dark", label: "Dark", icon: Moon },
    { v: "light", label: "Light", icon: Sun },
    { v: "system", label: "System", icon: Monitor },
  ];

  return (
    <Page>
      <PageHeader title="Settings" subtitle="Personalise Equidy." />
      <div className="space-y-4">
        <Section title="Appearance">
          <Row label="Theme">
            <div className="inline-flex rounded-xl border border-line p-0.5">
              {themes.map((t) => (
                <button key={t.v} onClick={() => s.set({ theme: t.v })} className={cn("flex items-center gap-1.5 rounded-[10px] px-3 py-1.5 text-xs font-medium", s.theme === t.v ? "bg-elevated text-fg" : "text-muted hover:text-fg")}>
                  <t.icon className="h-3.5 w-3.5" /> {t.label}
                </button>
              ))}
            </div>
          </Row>
          <Row label="Display currency" hint="Values are converted at fixed reference rates.">
            <select className="input h-9 w-28" value={s.currency} onChange={(e) => s.set({ currency: e.target.value })}>
              {["USD", "EUR", "GBP", "INR", "JPY"].map((c) => <option key={c}>{c}</option>)}
            </select>
          </Row>
          <Row label="Live price updates" hint="Animate the simulated market feed every few seconds.">
            <Toggle checked={s.liveTicks} onChange={(v) => s.set({ liveTicks: v })} label="Live price updates" />
          </Row>
        </Section>

        <Section title="AI assistant" desc="How Equidy answers your questions.">
          <Row label="Engine" hint={status?.ai ? "Responses are generated by Claude via the Equidy server." : "Set ANTHROPIC_API_KEY on the server to enable Claude. The built-in offline engine is used meanwhile."}>
            <div className="flex items-center gap-2">
              {status && (status.ai ? <span className="chip"><Cpu className="h-3 w-3 text-accent" />Claude · {status.model}</span> : <span className="chip"><WifiOff className="h-3 w-3" />{status.online ? "Offline engine" : "Server unreachable · offline engine"}</span>)}
              <button className="btn-ghost p-1.5" onClick={() => aiStatus(true).then(setStatus)} aria-label="Re-check AI status"><RefreshCw className="h-3.5 w-3.5" /></button>
            </div>
          </Row>
          <Row label="Response style">
            <Segmented value={s.responseStyle} options={["concise", "balanced", "detailed"] as const} onChange={(v) => s.set({ responseStyle: v })} />
          </Row>
          <Row label="Risk profile" hint="Used to tailor portfolio suggestions.">
            <Segmented value={s.riskProfile} options={["conservative", "moderate", "aggressive"] as const} onChange={(v) => s.set({ riskProfile: v })} />
          </Row>
        </Section>

        <Section title="Analytics">
          <Row label="Risk-free rate" hint="Used for Sharpe, Sortino and alpha.">
            <div className="relative w-28">
              <input type="number" step={0.25} className="input num h-9 pr-8" value={+(s.riskFree * 100).toFixed(2)} onChange={(e) => s.set({ riskFree: Math.max(0, Number(e.target.value)) / 100 })} />
              <span className="pointer-events-none absolute right-3 top-1/2 -translate-y-1/2 text-xs text-muted">%</span>
            </div>
          </Row>
        </Section>

        <Section title="Data" desc="Everything is stored locally in this browser.">
          <Row label="Export data" hint="Download settings, portfolio and conversations as JSON.">
            <button className="btn-outline" onClick={exportData}><Download className="h-4 w-4" /> Export</button>
          </Row>
          <Row label="Reset portfolio" hint="Restore the sample holdings and watchlist.">
            {confirm === "portfolio" ? (
              <div className="flex gap-2"><button className="btn-ghost" onClick={() => setConfirm(null)}>Cancel</button><button className="btn bg-down text-white" onClick={() => { resetPortfolio(); setConfirm(null); }}>Confirm reset</button></div>
            ) : <button className="btn-outline" onClick={() => setConfirm("portfolio")}><RotateCcw className="h-4 w-4" /> Reset</button>}
          </Row>
          <Row label="Delete all conversations">
            {confirm === "chats" ? (
              <div className="flex gap-2"><button className="btn-ghost" onClick={() => setConfirm(null)}>Cancel</button><button className="btn bg-down text-white" onClick={() => { clearChats(); setConfirm(null); }}>Delete all</button></div>
            ) : <button className="btn-outline text-down" onClick={() => setConfirm("chats")}><Trash2 className="h-4 w-4" /> Delete</button>}
          </Row>
        </Section>
      </div>
    </Page>
  );
}
